from apscheduler.schedulers.asyncio import AsyncIOScheduler

from db import (
    reset_habits,
    get_all_users,
    create_daily_tasks,
    check_achievements,
    log_daily_habits
)

# job_defaults без этого раньше означали: если процесс был недоступен
# (Railway передеплой, краткий даунтайм) ровно в момент срабатывания
# job'а — APScheduler по умолчанию (misfire_grace_time=1 секунда) просто
# СПИСЫВАЕТ этот запуск как пропущенный, без повтора. Для job'ов вроде
# "разослать напоминание в 06:00" это означало: пропустили минуту —
# пользователь не получит напоминание весь день, до следующего цикла.
# misfire_grace_time=1800 — если планировщик отстал/был недоступен, но
# спохватился в течение получаса, пропущенный запуск всё равно выполнится
# (просто один раз, не по одному на каждую пропущенную минуту — за это
# отвечает coalesce=True). max_instances=1 — на случай, если один прогон
# job'а (проход по всем пользователям) не успел закончиться до следующего
# тика, не даём двум прогонам одного и того же job'а работать параллельно.
scheduler = AsyncIOScheduler(
    job_defaults={
        "misfire_grace_time": 1800,
        "coalesce": True,
        "max_instances": 1,
    }
)


# =====================================
# НОВЫЙ ДЕНЬ
# =====================================

def new_day():

    print("=" * 40)
    print("🌅 Новый день")

    try:

        # Сначала — снимок состояния каждой привычки за уходящий день
        # (нужен для еженедельного AI-анализа по привычкам), и только
        # потом сброс, иначе completed уже обнулится.
        log_daily_habits()

        print("📒 Журнал дня сохранён")

    except Exception as e:

        print(f"❌ Ошибка записи журнала дня: {e}")

    try:

        # Сбросить выполнение привычек
        reset_habits()

        print("✅ Привычки сброшены")

    except Exception as e:

        print(f"❌ Ошибка сброса привычек: {e}")

    users = get_all_users()

    for user in users:

        try:

            telegram_id = user["telegram_id"]

            # Создать ежедневные задания
            create_daily_tasks(telegram_id)

            # Проверить достижения
            check_achievements(telegram_id)

        except Exception as e:

            print(f"Ошибка пользователя {user['telegram_id']}: {e}")

    print("✅ Ежедневные задания созданы")
    print("🏁 Новый день подготовлен")
    print("=" * 40)


