def _norm(text):
    return " ".join(str(text or "").lower().replace("ё", "е").split())


def detect_scenarios(text):
    """До двух ключей сценариев из GUIDE по тексту сообщения, в порядке важности. [] — обычный вопрос."""
    norm = _norm(text)
    if not norm or len(norm) > LONG_MESSAGE:
        return []
    found = []
    for key, rx in _COMPILED:
        if key == "smalltalk" and len(norm) > SMALLTALK_MAX_CHARS:
            continue
        if rx.search(norm):
            found.append(key)
    if "app_help" not in found and _APP_QUESTION.search(norm) and _APP_WORDS.search(norm) and "pair" not in found:
        found.insert(0, "app_help")
    return found[:MAX_SCENARIOS]


def detect_mood(text):
    """Одно из: воодушевлён, нейтрально, устал, расстроен, раздражён, тревожен — по словам (без вызова модели)."""
    norm = _norm(text)
    if not norm or len(norm) > LONG_MESSAGE:
        return "нейтрально"
    for mood, rx in _MOOD_RE:
        if rx.search(norm):
            return mood
    return "нейтрально"


