def _code_name(path):
    """Имя заметки о файле: без точки расширения — иначе Obsidian примет ссылку [[x.py]] за вложение, а не за заметку."""
    return path.rsplit(".", 1)[0].replace("/", " · ") + (" (js)" if path.endswith(".js") else " (html)" if path.endswith(".html") else "")


def _safe(name):
    return re.sub(r'[\\/:*?"<>|#^\[\]]', "-", name).strip()


def _write(rel, text, overwrite=True):
    path = os.path.join(BRAIN, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not overwrite and os.path.exists(path):
        return
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text.rstrip() + "\n")


def _links(names):
    return ", ".join(f"[[{n}]]" for n in names)


def build_features():
    for name, (body, links) in FEATURES.items():
        code = [f for f, feats in CODE.items() if name in feats]
        decisions = [d for d in DECISIONS if d[2] == name]
        text = [f"# {name}", "", body, "", f"Связано: {_links(links)}"]
        if code:
            text += ["", "Код: " + ", ".join(f"[[{_code_name(c)}]]" for c in code)]
        if decisions:
            text += ["", "Решения владельца:"] + [f"- {d} — {t}" for d, t, _ in decisions]
        text += ["", "#функция"]
        _write(f"Функции/{_safe(name)}.md", "\n".join(text), overwrite=False)


