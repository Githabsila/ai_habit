def _docstring(path):
    try:
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            src = fh.read()
    except OSError:
        return ""
    if path.endswith(".py"):
        try:
            doc = ast.get_docstring(ast.parse(src)) or ""
        except SyntaxError:
            doc = ""
        return doc.strip()
    return ""


def build_code():
    for path, feats in CODE.items():
        doc = _docstring(path)
        first = "\n".join(doc.splitlines()[:12]) if doc else "Описание — в самом файле."
        text = [f"# {path}", "", first, "", f"Функции: {_links(feats)}", "", "#код"]
        _write(f"Код/{_code_name(path)}.md", "\n".join(text))


def build_history():
    log = subprocess.run(["git", "log", "--format=%h|%ad|%s", "--date=format:%d.%m.%Y", "origin/main"], cwd=ROOT, capture_output=True, text=True).stdout
    for line in log.splitlines():
        sha, date, subject = line.split("|", 2)
        pr = re.search(r"\(#(\d+)\)\s*$", subject)
        if not pr:
            continue
        title = re.sub(r"\s*\(#\d+\)\s*$", "", subject)
        low = title.lower()
        feats = sorted({f for k, f in KEYWORDS.items() if k in low})
        text = [f"# PR #{pr.group(1)} · {date}", "", title, "", f"Коммит `{sha}` · https://github.com/Githabsila/ai_habit/pull/{pr.group(1)}",
                "", "Затронуто: " + (_links(feats) if feats else "[[ADAM]]"), "", "#история"]
        _write(f"История/PR {int(pr.group(1)):03d}.md", "\n".join(text))


