"""
adam_messages.py

Единый источник текстов AI-наставника «AI ADAM» для всех проактивных
уведомлений (дневное/вечернее напоминание по плану дня, утренние
напоминания по привычкам, поздравления, периодические сообщения
в начале/конце недели и месяца).

Согласно промту:
  - каждое уведомление — новое, не повторяется день в день (поэтому тут
    пул из нескольких вариантов на каждый случай, а не один шаблон);
  - в конце почти каждого сообщения — 1 случайный смайлик из набора;
  - сообщения должны быть живыми, эмпатичными, но требовательными, без
    упоминания Adam Coin как реальных денег.
"""

import random

EMOJI_POOL = ["👍", "🎉", "🔥", "💪", "🚀", "⏰", "⚡️", "🧠", "🎯", "🏅", "🥇", "👊"]


def random_emoji() -> str:
    return random.choice(EMOJI_POOL)


def pick(templates: list[str], **kwargs) -> str:
    """Выбрать случайный шаблон и подставить в него параметры + случайный
    смайлик (если в шаблоне есть плейсхолдер {emoji})."""
    template = random.choice(templates)
    return template.format(emoji=random_emoji(), **kwargs)


